-- Prints the app's whole database (public schema, storage rules, realtime) as SQL, one statement per row,
-- in an order that loads into a fresh Supabase. Run it in the SQL editor or through the MCP tool and save
-- the output as supabase/schema.sql. Data, cron jobs and secrets are left out on purpose.
with
tabs as (
  select c.oid, c.relname, c.relrowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
funcs as (
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
stmts(ord, name, sql) as (
  select 0, '', 'set check_function_bodies = off;'
  union all
  select 1, e.extname, format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname in ('vector', 'unaccent', 'pg_trgm', 'pgcrypto', 'uuid-ossp', 'pg_net')
  union all
  select 2, t.relname, format(E'create table public.%I (\n%s\n);', t.relname, (
    select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
      case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
      case when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
      case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
    from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tabs t
  union all
  select case when co.contype = 'f' then 4 else 3 end, t.relname || '.' || co.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tabs t on t.oid = co.conrelid
  union all
  select 5, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join tabs t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
  union all
  select 6, f.proname || '(' || f.args || ')', pg_get_functiondef(f.oid) || ';' from funcs f
  union all
  select 7, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join tabs t on t.oid = tg.tgrelid where not tg.tgisinternal
  union all
  select 8, t.relname, format('alter table public.%I enable row level security;', t.relname) from tabs t where t.relrowsecurity
  union all
  select 9, p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
      array_to_string(p.roles, ', '),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
  union all
  select 10, t.relname, format('revoke all on public.%I from public, anon, authenticated;', t.relname) from tabs t
  union all
  select 11, g.table_name || '.' || g.grantee || '.' || g.privilege_type,
    format('grant %s on public.%I to %I;', lower(g.privilege_type), g.table_name, g.grantee)
  from information_schema.role_table_grants g join tabs t on t.relname = g.table_name
  where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated')
  union all
  select 12, f.proname || '(' || f.args || ')', format('revoke all on function public.%I(%s) from public, anon, authenticated;', f.proname, f.args) from funcs f
  union all
  select 13, f.proname || '(' || f.args || ').' || r.rolname,
    format('grant execute on function public.%I(%s) to %I;', f.proname, f.args, r.rolname)
  from funcs f cross join pg_roles r
  where r.rolname in ('anon', 'authenticated') and has_function_privilege(r.oid, f.oid, 'execute')
  union all
  select 14, pt.tablename, format('alter publication supabase_realtime add table public.%I;', pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
  union all
  select 15, b.id, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %L) on conflict (id) do nothing;',
    b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'), b.allowed_mime_types)
  from storage.buckets b
)
select sql from stmts order by ord, name;
